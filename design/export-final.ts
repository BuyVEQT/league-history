/**
 * Writes design/prototype/final.js (window.FINAL) for the prototype's Cup page, from the same capture and analytics the
 * site uses: data/leagues/caboclo/caboclo-final.json + src/lib/analytics/cabocloFinal.ts.
 * Run: node --experimental-strip-types design/export-final.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { finalTimeline, lastShotWhatIf, type CabocloFinal } from "../src/lib/analytics/cabocloFinal.ts";

const root = join(import.meta.dirname, "..");
const data = (f: string) => JSON.parse(readFileSync(join(root, "data", "leagues", "caboclo", f), "utf8"));
const final = data("caboclo-final.json") as CabocloFinal;
const managers = data("managers.json") as { id: string; name: string }[];
const brunoRank = (data("2019.json").players as { name: string; actualRank: number }[]).find((p) => p.name === "Bruno Caboclo")?.actualRank ?? null;

const out = {
  final,
  managers,
  brunoRank,
  timeline: finalTimeline(final, "matt", "jacob-g"),
  whatIf: lastShotWhatIf(final, "matt", "jacob-g"),
};
writeFileSync(
  join(root, "design", "prototype", "final.js"),
  `/* Generated by design/export-final.ts from src/lib/analytics/cabocloFinal.ts */\nwindow.FINAL = ${JSON.stringify(out)};\n`,
);
console.log("design/prototype/final.js written");
